"""Turn the prompt files in prompts/ into wrapping LaTeX in prompt_text.tex.

Run from this folder after a prompt changes: python3 make_prompts.py
Each prompt line becomes one paragraph in a monospaced box, so long lines wrap on the page.
"""
import pathlib

PROMPTS = [
    ("System Prompt", "worker_system.txt"),
    ("Extract Prompt (M2)", "extract_prompt.txt"),
    ("Review Prompt (M2)", "review_prompt.txt"),
    ("Consolidation Prompt (M2)", "consolidate_prompt.txt"),
    ("Reflect Prompt (M4)", "reflect_prompt.txt"),
]
SPECIAL = {"\\": r"\textbackslash{}", "&": r"\&", "%": r"\%", "$": r"\$", "#": r"\#",
           "_": r"\_", "{": r"\{", "}": r"\}", "~": r"\textasciitilde{}", "^": r"\textasciicircum{}"}
BREAK_AFTER = set(",:/|=")


def tex(line):
    out = []
    for ch in line:
        out.append(SPECIAL.get(ch, ch))
        if ch in BREAK_AFTER:
            out.append(r"\allowbreak{}")
    return "".join(out)


here = pathlib.Path(__file__).parent
parts = []
for title, name in PROMPTS:
    lines = (here / "prompts" / name).read_text().rstrip("\n").split("\n")
    body = []
    for line in lines:
        body.append(r"\par\smallskip " + tex(line) if line.strip() else r"\par\medskip")
    parts.append("\\section{\\uppercase{%s}}\n\\begin{promptbox}\n%s\n\\end{promptbox}\n"
                 % (title, "\n".join(body)))
(here / "prompt_text.tex").write_text("% Generated by make_prompts.py from prompts/*.txt. Do not edit.\n\n"
                                  + "\n".join(parts))
