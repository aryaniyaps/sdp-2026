"""Writes the result tables of the report's results chapter from the stored run records, so every number
in the chapter is regenerated by one command rather than typed by hand:

    python3 benchmark/export_tex.py --run locomo-final --properties properties-final [--properties-after RUN]

Output: one file per table, report/latex/5/tables/<name>.tex, labelled tab:bench-<name>."""
import argparse
import json
from pathlib import Path

BENCH = Path(__file__).resolve().parent
ROOT = BENCH.parent
OUT = ROOT / "report/latex/5/tables"

NAMES = {
    "enhanced": "Memory engine",
    "raw_hybrid": "Plain retrieval",
    "recent_window": "Recent window",
    "full_context": "Whole conversation",
    "no_memory": "No memory",
    "assertions_only": "Assertions only",
    "no_graph": "Without graph",
    "no_consolidation": "Without consolidation",
}
MAIN = ["enhanced", "raw_hybrid", "recent_window", "full_context", "no_memory"]
ABLATIONS = ["assertions_only", "no_graph", "no_consolidation"]
CATEGORIES = [("single_hop", "Single-hop"), ("multi_hop", "Multi-hop"), ("temporal", "Temporal"),
              ("open_domain", "Open-domain")]


def pct(x, digits=1):
    return "--" if x is None else f"{100 * x:.{digits}f}"


def num(x, digits=0):
    return "--" if x is None else f"{x:,.{digits}f}"


def signed(x):
    return "--" if x is None else f"{100 * x:+.1f}"


def interval(ci):
    return "--" if not ci else f"[{100 * ci[0]:+.1f}, {100 * ci[1]:+.1f}]"


def table(label, caption, spec, header, rows, note=None):
    lines = ["\\begin{table}[H]", f"\\caption{{{caption}}}", f"\\label{{tab:bench-{label}}}", "\\centering",
             "\\begin{reporttable}", f"\\begin{{tabularx}}{{\\textwidth}}{{{spec}}}", "\\hline",
             " & ".join(f"\\textbf{{{h}}}" for h in header) + " \\\\", "\\hline"]
    lines += [" & ".join(str(c) for c in row) + " \\\\ \\hline" for row in rows]
    lines += ["\\end{tabularx}", "\\end{reporttable}"]
    if note:
        lines += ["\\par\\smallskip{\\footnotesize " + note + "}"]
    lines += ["\\end{table}", ""]
    return "\n".join(lines)


def main_results(r):
    c = r["conditions"]
    rows = []
    for name in MAIN + ABLATIONS:
        if name not in c:
            continue
        x = c[name]
        rows.append([NAMES[name], x["answered"], pct(x.get("jev_accuracy")), pct(x.get("gpt4omini_accuracy")),
                     pct(x.get("f1")), pct(x.get("bleu1")), num(x.get("context_tokens_mean")),
                     num(x.get("reader_seconds_p50"), 1)])
    return table("main", "LoCoMo results by condition (all ten conversations, categories 1--4)",
                 "|l|r|r|r|r|r|r|>{\\raggedleft\\arraybackslash}X|",
                 ["Condition", "n", "Jev", "GPT-4o-mini", "F1", "BLEU-1", "Tokens", "Reader s"], rows,
                 "Jev and GPT-4o-mini: percentage of answers judged correct against the gold answer with Mem0's LoCoMo "
                 "rubric. F1 and BLEU-1: Mem0's token overlap with the gold answer. Context tokens: mean tokens given "
                 "to the reader besides the question. Reader s: median seconds per answer. The last three rows are on the 300-question stratified sample.")


def paired(r, judge):
    p = r["paired_vs_enhanced"].get(judge) or {}
    rows = []
    for name in MAIN[1:] + ABLATIONS:
        if name in p and p[name]:
            x = p[name]
            rows.append([NAMES[name], x["n"], signed(x["difference"]), interval(x["ci95"]),
                         interval(x.get("cluster_ci95"))])
    return table(f"paired-{judge}", "Accuracy of the memory engine minus each other condition, same questions "
                 f"({'Jev' if judge == 'jev' else 'GPT-4o-mini'})", "|Y|r|r|c|c|",
                 ["Compared with", "n", "Difference (pts)", "95\\% CI, questions", "95\\% CI, conversations"], rows,
                 "Paired bootstrap with 2,000 resamples, over questions and over whole conversations (cluster "
                 "bootstrap). A positive difference means the memory engine answered more questions correctly.")


def categories(r):
    c = r["conditions"]
    rows = []
    for key, label in CATEGORIES:
        n = c["enhanced"]["categories"].get(key, {}).get("n")
        rows.append([label, n] + [pct(c[name]["categories"].get(key, {}).get("jev_accuracy"))
                                  for name in MAIN if name in c])
    header = ["Category", "n"] + [NAMES[name] for name in MAIN if name in c]
    return table("categories", "Accuracy by LoCoMo question category (Jev, \\%)",
                 "|l|r|" + "Y|" * (len(header) - 2), header, rows)


def held_out(r):
    h = r.get("held_out")
    if not h:
        return ""
    c, a = h["conditions"], r["conditions"]
    rows = [[NAMES[name], pct(a[name].get("jev_accuracy")), pct(c[name].get("jev_accuracy")),
             pct(c[name].get("gpt4omini_accuracy"))] for name in MAIN if name in c]
    return table("held-out", "All ten conversations against the eight never used for diagnosis",
                 "|Y|r|r|r|", ["Condition", "Jev, all ten", "Jev, held-out eight", "GPT-4o-mini, held-out eight"],
                 rows, f"Held-out conversations: {', '.join(h['conversations'])}.")


def retrieval(r):
    c = r["conditions"]
    keys = [("session_recall@5", "Evidence session in top 5"), ("session_recall@10", "Evidence session in top 10"),
            ("session_recall_all@10", "All evidence sessions in top 10"),
            ("packed_session_recall", "Evidence session in the packed context"),
            ("packed_turn_recall", "Evidence turn in the packed context")]
    names = [n for n in ("enhanced", "raw_hybrid", "assertions_only") if n in c]
    rows = [[label] + [pct(c[n]["retrieval"].get(k)) for n in names] for k, label in keys]
    rows.append(["Source quotes checked"] + [num(c[n].get("quotes_checked")) for n in names])
    rows.append(["Quotes exactly matching the cited turn"] + [pct(c[n].get("quote_exactness"), 2) for n in names])
    rows.append(["Recall latency, ms (p50 / p95)"] +
                [f"{num(c[n].get('recall_ms_p50'))} / {num(c[n].get('recall_ms_p95'))}" for n in names])
    return table("retrieval", "Retrieval against LoCoMo's evidence labels (\\%)", "|Y|" + "r|" * len(names),
                 ["Measure"] + [NAMES[n] for n in names], rows)


def repeats(r):
    rows = []
    for name, x in r["repeats"].items():
        if not x.get("questions"):
            continue
        rows.append([NAMES[name], x["questions"], ", ".join(pct(a) for a in x["accuracy_by_repeat"]),
                     pct(x.get("accuracy_stdev")), pct(x.get("verdict_flip_rate"))])
    return table("repeats", "Run-to-run variation: the reader asked three times on the 300-question sample (Jev)",
                 "|Y|r|c|r|r|", ["Condition", "n", "Accuracy, runs 0/1/2 (\\%)", "SD (pts)", "Verdicts changed (\\%)"],
                 rows, "Verdicts changed: share of questions whose verdict differs in at least one repeat.")


def agreement(r):
    a = r.get("judge_agreement")
    if not a:
        return ""
    rows = [["All graded answers, every condition", num(a["n"]), pct(a["agreement"]), num(a["kappa"], 3)]]
    return table("judges", "Agreement of the two judges", "|Y|r|r|r|",
                 ["Answers", "n", "Same verdict (\\%)", "Cohen's $\\kappa$"], rows)


def criteria(r, config):
    rule, got = config["criteria"], r.get("criteria") or {}
    held = (r.get("held_out") or {}).get("criteria") or {}
    yes = lambda v: "--" if v is None else ("pass" if v else "fail")
    rows = [
        ["Memory engine beats no memory", f"by $\\geq$ {pct(rule['beats_no_memory_by'], 0)} pts",
         yes(got.get("beats_no_memory")), yes(held.get("beats_no_memory"))],
        ["Memory engine beats the recent window", "conversation CI above 0",
         yes(got.get("beats_recent_window")), yes(held.get("beats_recent_window"))],
        ["Memory engine not below plain retrieval", "conversation CI not wholly below 0",
         yes(got.get("not_below_raw_hybrid")), yes(held.get("not_below_raw_hybrid"))],
        ["Memory engine above plain retrieval (not required)", "conversation CI above 0",
         yes(got.get("above_raw_hybrid")), yes(held.get("above_raw_hybrid"))],
        ["Close to the whole conversation", f"within {pct(rule['within_full_context_by'], 0)} pts",
         yes(got.get("within_full_context")), yes(held.get("within_full_context"))],
        ["Uses at most half its tokens", f"share $\\leq$ {rule['max_token_share_of_full_context']}"
         f" (got {num(got.get('token_share_of_full_context'), 2)})",
         yes(got.get("token_share_ok")), yes(held.get("token_share_ok"))],
        ["Every source quote exact", "100\\%", yes(got.get("quotes_exact")), yes(held.get("quotes_exact"))],
    ]
    return table("criteria", "Success criteria fixed before the test run (Jev)", "|Y|Y|c|c|",
                 ["Criterion", "Threshold", "All ten", "Held-out eight"], rows)


def published(r, pub):
    c = r["conditions"]
    ours_full, ours = c.get("full_context", {}), c["enhanced"]
    rows = [[name, f"{j:.2f}", num(pub["locomo_context_tokens"].get(name)), f"{j - pub['locomo_overall_j']['Full-context']:+.2f}"]
            for name, j in pub["locomo_overall_j"].items()]
    g = lambda x: None if x.get("gpt4omini_accuracy") is None else 100 * x["gpt4omini_accuracy"]
    if g(ours) is not None and g(ours_full) is not None:
        rows.append(["\\textbf{This work: whole conversation (Haiku 5.5)}", f"{g(ours_full):.2f}",
                     num(ours_full.get("context_tokens_mean")), "+0.00"])
        rows.append(["\\textbf{This work: memory engine (Haiku 5.5)}", f"{g(ours):.2f}",
                     num(ours.get("context_tokens_mean")), f"{g(ours) - g(ours_full):+.2f}"])
        raw = c.get("raw_hybrid", {})
        if g(raw) is not None:
            rows.append(["\\textbf{This work: plain retrieval (Haiku 5.5)}", f"{g(raw):.2f}",
                         num(raw.get("context_tokens_mean")), f"{g(raw) - g(ours_full):+.2f}"])
    return table("published", "Published LoCoMo results \\cite{chhikara2025mem0} beside this work (GPT-4o-mini judge)",
                 "|Y|r|r|r|", ["System", "J (\\%)", "Context tokens", "J minus own full context"], rows,
                 "Published systems answer with GPT-4o-mini; this work answers with Claude Haiku 5.5, so absolute "
                 "scores are not comparable. The last column compares each system with the full-context baseline "
                 "of its own study. Context tokens for published systems are from the Mem0 paper.")


def properties(runs):
    summaries = [(label, json.loads((BENCH / "runs" / run / "summary.json").read_text())) for label, run in runs]
    checks = sorted({k for _, s in summaries for k in s["checks"]})
    rows = []
    for k in checks:
        family, check = k.split(".", 1)
        rows.append([family.replace("_", " "), check.replace("_", " ")] +
                    [f"{s['checks'][k]['passed']}/{s['checks'][k]['n']}" if k in s["checks"] else "--"
                     for _, s in summaries])
    return table("properties", "Property suite: checks on the engine's stored state, no judge",
                 "|l|Y|" + "c|" * len(summaries), ["Family", "Check"] + [label for label, _ in summaries], rows)


def ingestion(r):
    i = r["ingestion"]
    hours = i["bank_seconds_sum"] / 3600
    rows = [["Conversations / sessions / turns", f"{i['banks']} / {i['sessions']} / {i['turns']:,}"],
            ["Characters retained", num(i["characters"])],
            ["Bank build time, summed over conversations", f"{hours:.1f} h"],
            ["Model time in extraction", f"{i['worker_ms'].get('worker_extract', 0) / 3.6e6:.1f} h"],
            ["Model time in consolidation", f"{i['worker_ms'].get('worker_consolidate', 0) / 3.6e6:.2f} h"],
            ["Jobs that failed permanently", i["permanently_failed_jobs"]]]
    return table("ingestion", "Cost of building memory for LoCoMo on one RTX 4070 laptop GPU (8 GB)", "|Y|r|",
                 ["Measure", "Value"], rows,
                 "Four conversations were built at a time, so summed build time exceeds wall-clock time.")


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--run", default="locomo-final")
    parser.add_argument("--properties", default="properties-final")
    parser.add_argument("--properties-after", help="property run after a fix made once the test run had finished")
    parser.add_argument("--out", type=Path, default=OUT)
    args = parser.parse_args()
    r = json.loads((BENCH / "runs" / args.run / "report.json").read_text())
    config = json.loads((BENCH / "config.json").read_text())
    pub = json.loads((BENCH / "published.json").read_text())
    runs = [("Test run", args.properties)] + ([("After fix", args.properties_after)] if args.properties_after else [])
    tables = {"criteria": criteria(r, config), "main": main_results(r), "paired-jev": paired(r, "jev"),
              "paired-gpt4omini": paired(r, "gpt4omini"), "held-out": held_out(r), "categories": categories(r),
              "retrieval": retrieval(r), "repeats": repeats(r), "judges": agreement(r), "published": published(r, pub),
              "properties": properties(runs), "ingestion": ingestion(r)}
    args.out.mkdir(parents=True, exist_ok=True)
    for name, text in tables.items():
        header = f"% Generated by benchmark/export_tex.py from benchmark/runs/{args.run}; do not edit by hand.\n"
        (args.out / f"{name}.tex").write_text(header + text)
    print(f"wrote {len(tables)} tables to {args.out}")

if __name__ == "__main__":
    main()
